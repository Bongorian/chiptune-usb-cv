#!/usr/bin/env python3
"""Deterministic host-generated DSP tables; no transcendental functions in the audio tick."""
from pathlib import Path
import math
root=Path(__file__).resolve().parents[1]/'src'
ratio=[2**(i/(12*256)) for i in range(3073)]
sine=[round(math.sin(i*2*math.pi/256)*32767) for i in range(256)]
decay=[math.exp(-i/16) for i in range(257)]
def literal(v):
 s=f'{v:.9g}'
 return s+'f' if '.' in s else f'{v:.1f}f'
(root/'math_lut.inc').write_text('static const float pitch_ratio[3073]={'+','.join(map(literal,ratio))+'};\nstatic const int16_t sine_lut[256]={'+','.join(map(str,sine))+'};\nstatic const float decay_lut[257]={'+','.join(f'{v:.9e}f' for v in decay)+'};\n')
lut=[]
for i in range(3072):
 hz=440*2**((60+i/256-69)/12)
 options=[]
 for o in range(8):
  f=min(255,max(0,round(511-8000000*2**o/(512*hz))))
  options.append((abs(8000000*2**o/(512*(511-f))-hz),o,f))
 _,o,f=min(options)
 lut.append(o<<8|f)
(root/'saa_pitch_lut.inc').write_text('/* MIDI 60..72 at 1/256-semitone intervals, generated by tools/generate_lut.py. */\nstatic const uint16_t saa_pitch_lut[3072]={'+','.join(map(str,lut))+'};\n')
